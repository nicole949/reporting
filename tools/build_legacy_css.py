"""Builds site/assets/legacy.css from the live v1 stylesheet (archive/v1-live/assets/app.css):
shell rules dropped, colours mapped to the v2 brand tokens, every rule scoped to `.v1` (ported page content)."""
import re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from v1lib import recolor, scope_css
root = pathlib.Path(__file__).resolve().parents[1]
src = (root / 'archive/v1-live/assets/app.css').read_text()
css = scope_css(recolor(src), '.v1', drop_shell=True)
# the filter bar is owned by app.css (same look on every page)
css = '\n'.join(l for l in css.split('\n') if not re.match(r'^\.v1 \.filters\b', l))
extra = (root / 'tools/legacy_extra.css').read_text() if (root / 'tools/legacy_extra.css').exists() else ''
(root / 'site/assets/legacy.css').write_text('/* GENERATED by tools/build_legacy_css.py from the live v1 stylesheet — do not edit here. */\n' + css + '\n' + extra)
print('legacy.css', len(css))
